-- VERITAS system-of-record schema (PostgreSQL; also runs on H2 in PostgreSQL mode for local dev).
-- Chunks, facts and embeddings live in the evidence store owned by the AI service (pgvector).

CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(254) NOT NULL UNIQUE,
    password_hash   VARCHAR(100) NOT NULL,
    display_name    VARCHAR(120) NOT NULL,
    role            VARCHAR(20)  NOT NULL,
    guest           BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE investigations (
    id              UUID PRIMARY KEY,
    owner_id        BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title           VARCHAR(200) NOT NULL,
    description     VARCHAR(2000),
    demo            BOOLEAN NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_investigations_owner ON investigations(owner_id);

CREATE TABLE documents (
    id              UUID PRIMARY KEY,
    investigation_id UUID NOT NULL REFERENCES investigations(id) ON DELETE CASCADE,
    filename        VARCHAR(255) NOT NULL,
    content_type    VARCHAR(120),
    size_bytes      BIGINT NOT NULL,
    sha256          VARCHAR(64) NOT NULL,
    storage_path    VARCHAR(500) NOT NULL,
    status          VARCHAR(20) NOT NULL,
    error_code      VARCHAR(40),
    error_message   VARCHAR(500),
    kind            VARCHAR(20),
    title           VARCHAR(300),
    doc_role        VARCHAR(20),
    doc_date        VARCHAR(10),
    pages           INTEGER,
    chunks          INTEGER,
    facts           INTEGER,
    ocr_used        BOOLEAN,
    quality         DOUBLE PRECISION,
    security_flags  INTEGER,
    warnings        VARCHAR(2000),
    ingest_ms       BIGINT,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    indexed_at      TIMESTAMP WITH TIME ZONE
);
CREATE INDEX ix_documents_investigation ON documents(investigation_id);
CREATE UNIQUE INDEX ux_documents_investigation_sha ON documents(investigation_id, sha256);

CREATE TABLE questions (
    id              UUID PRIMARY KEY,
    investigation_id UUID NOT NULL REFERENCES investigations(id) ON DELETE CASCADE,
    asked_by        BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    text            VARCHAR(1000) NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_questions_investigation ON questions(investigation_id);

CREATE TABLE answers (
    id              UUID PRIMARY KEY,
    question_id     UUID NOT NULL UNIQUE REFERENCES questions(id) ON DELETE CASCADE,
    verdict_status  VARCHAR(30) NOT NULL,
    headline        VARCHAR(300) NOT NULL,
    confidence      DOUBLE PRECISION NOT NULL,
    engine          VARCHAR(30) NOT NULL,
    payload         TEXT NOT NULL,          -- the complete structured answer (claims, evidence, graph...)
    latency_ms      BIGINT NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE claims (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    answer_id       UUID NOT NULL REFERENCES answers(id) ON DELETE CASCADE,
    claim_key       VARCHAR(10) NOT NULL,
    position        INTEGER NOT NULL,
    text            VARCHAR(2000) NOT NULL,
    status          VARCHAR(30) NOT NULL,
    kind            VARCHAR(20) NOT NULL,
    source          VARCHAR(10) NOT NULL
);
CREATE INDEX ix_claims_answer ON claims(answer_id);

CREATE TABLE citations (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id        BIGINT NOT NULL REFERENCES claims(id) ON DELETE CASCADE,
    evidence_key    VARCHAR(10) NOT NULL,
    document_id     UUID REFERENCES documents(id) ON DELETE SET NULL,
    chunk_id        VARCHAR(120) NOT NULL,
    page            INTEGER,
    section         VARCHAR(500),
    stance          VARCHAR(20) NOT NULL,
    quote           VARCHAR(2000) NOT NULL
);
CREATE INDEX ix_citations_claim ON citations(claim_id);

CREATE TABLE conflicts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    answer_id       UUID NOT NULL REFERENCES answers(id) ON DELETE CASCADE,
    conflict_key    VARCHAR(20) NOT NULL,
    severity        VARCHAR(10) NOT NULL,
    status          VARCHAR(20) NOT NULL,
    summary         VARCHAR(500) NOT NULL
);
CREATE INDEX ix_conflicts_answer ON conflicts(answer_id);

CREATE TABLE investigation_events (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    investigation_id UUID NOT NULL REFERENCES investigations(id) ON DELETE CASCADE,
    type            VARCHAR(40) NOT NULL,
    message         VARCHAR(500) NOT NULL,
    detail          VARCHAR(2000),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_events_investigation ON investigation_events(investigation_id, created_at);
